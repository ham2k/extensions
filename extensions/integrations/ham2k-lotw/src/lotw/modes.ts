const byPair = new Map(adifMap.map(([mode, submode, lotw]) => [`${mode}|${submode}`, lotw]))
// Older logs put a submode's name in MODE (MODE=USB, MODE=JS8).
const byName = new Map(adifMap.map(([mode, submode, lotw]) => [submode || mode, lotw]))

/**
 * The mode LoTW signs for an ADIF MODE and SUBMODE, or undefined when LoTW
 * takes neither. A submode LoTW knows decides before its mode does.
 */
export function lotwModeFor(mode: string, submode?: string): string | undefined {
  const parent = mode.toUpperCase()
  const child = submode?.toUpperCase()
  return (
    (child ? (byPair.get(`${parent}|${child}`) ?? byName.get(child)) : undefined) ??
    byPair.get(`${parent}|`) ??
    byName.get(parent) ??
    (modes.has(parent) ? parent : undefined)
  )
}
